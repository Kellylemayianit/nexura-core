// Builds worker-single.js: every module in ONE file, for pasting into the Cloudflare dashboard editor.
// Run: node scripts/bundle.mjs   (no dependencies)
import { readFileSync, writeFileSync } from 'node:fs';

const order = ['fsm.js', 'engine.js', 'simulate.js', 'handler.js'];
const strip = (src) =>
  src
    .split('\n')
    .filter((l) => !/^import\s/.test(l) && !/^export\s*\{/.test(l))
    .map((l) => l.replace(/^export\s+(const|let|function|async function|class)\s/, '$1 '))
    .join('\n');

let out = '// AUTO-GENERATED by scripts/bundle.mjs. Paste this whole file into a Cloudflare Worker.\n\n';
for (const f of order) out += `// ---- ${f} ----\n${strip(readFileSync(new URL(`../src/${f}`, import.meta.url), 'utf8'))}\n\n`;
out += `// ---- entry ----
const store = createStore();

export default {
  fetch(request, env) {
    return handle(request, store, { apiKey: env && env.API_KEY });
  },
};
`;
writeFileSync(new URL('../worker-single.js', import.meta.url), out);
console.log('wrote worker-single.js', out.length, 'bytes');
